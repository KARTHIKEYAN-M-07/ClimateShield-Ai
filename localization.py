def translate(key: str, lang: str = "en", **values: object) -> str:
    """Return a catalog value; missing keys and placeholders fail loudly."""
    if lang not in TRANSLATIONS:
        raise KeyError(f"Unsupported language: {lang}")
    try:
        template = TRANSLATIONS[lang][key]
    except KeyError as exc:
        raise KeyError(f"Missing {lang!r} translation for {key!r}") from exc
    return template.format(**values)


def missing_translation_keys() -> Dict[str, set[str]]:
    """Return catalog keys absent from any supported language."""
    all_keys = set().union(*(catalog.keys() for catalog in TRANSLATIONS.values()))
    return {
        lang: all_keys - set(catalog)
        for lang, catalog in TRANSLATIONS.items()
    }


def category_label(category: str, lang: str = "en") -> str:
    """Translate a risk category while preserving its internal English identifier."""
    key = f"risk.category.{category}"
    if key not in TRANSLATIONS[lang]:
        return category
    return translate(key, lang)
